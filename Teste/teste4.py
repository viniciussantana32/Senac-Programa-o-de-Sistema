def mostrar_perfil(nome, idade, cidade):
    print("----- Perfil do Usuário -----")
    print(f"Nome: {nome}")
    print(f"Idade: {idade}")
    print(f"Cidade: {cidade}")

# Exemplo de uso da função
mostrar_perfil("João", 25, "São Paulo")
mostrar_perfil("Maria", 30, "Rio de Janeiro")
mostrar_perfil("Pedro", 35, "Brasília")